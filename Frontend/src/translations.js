/**
 * Helper to translate known dynamic specification keys (e.g. "Fuel Type" -> "எரிபொருள் வகை")
 */
export function translateSpecKey(key, lang = 'en') {
  if (!key) return '';
  const cleanKey = key.toString().trim().toLowerCase().replace(/[^a-z0-9]/g, '');
  const keyMap = {
    usage: 'specKeys.usage',
    fueltype: 'specKeys.fuelType',
    cookingsurface: 'specKeys.cookingSurface',
    cookingcapacity: 'specKeys.cookingCapacity',
    burnersize: 'specKeys.burnerSize',
    stoveweight: 'specKeys.stoveWeight',
    weight: 'specKeys.stoveWeight',
    dimensions: 'specKeys.dimensions',
    material: 'specKeys.material',
    suitablefor: 'specKeys.suitableFor',
    application: 'specKeys.application',
    features: 'specKeys.features',
    powersource: 'specKeys.powerSource',
    capacity: 'specKeys.capacity',
  };

  const translationPath = keyMap[cleanKey];
  if (translationPath) {
    const parts = translationPath.split('.');
    const langDict = translations[lang] || translations.en;
    if (langDict && langDict[parts[0]] && langDict[parts[0]][parts[1]]) {
      return langDict[parts[0]][parts[1]];
    }
  }
  return key;
}

