/**
 * Helper to translate category names (e.g. "Stoves" -> "அடுப்புகள்")
 */
export function translateCategoryName(cat, lang = 'en') {
  if (!cat) return '';
  const cleanCat = cat.toString().trim().toLowerCase().replace(/[^a-z0-9]/g, '');
  const langDict = translations[lang] || translations.en;
  if (langDict && langDict.categories && langDict.categories[cleanCat]) {
    return langDict.categories[cleanCat];
  }
  return cat;
}

